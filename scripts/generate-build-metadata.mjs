import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";

function readBuildValue(name, fallback) {
  const value = process.env[name]?.trim();
  return value || fallback;
}

function gitValue(args, fallback) {
  try {
    return execFileSync("git", args, { encoding: "utf8" }).trim() || fallback;
  } catch {
    return fallback;
  }
}

const metadata = {
  variant: "variant_b_discover",
  branch: readBuildValue("WORKERS_CI_BRANCH", gitValue(["branch", "--show-current"], "local")),
  commitSha: readBuildValue("WORKERS_CI_COMMIT_SHA", gitValue(["rev-parse", "HEAD"], "local")),
  buildTimestamp: readBuildValue("WORKERS_CI_BUILD_TIMESTAMP", new Date().toISOString()),
};

const outputDirectory = new URL("../src/generated/", import.meta.url);
const outputFile = new URL("build-metadata.js", outputDirectory);
await mkdir(outputDirectory, { recursive: true });
await writeFile(
  outputFile,
  `// Generated by scripts/generate-build-metadata.mjs. Do not edit.\nexport const buildMetadata = ${JSON.stringify(metadata, null, 2)};\n`,
);
